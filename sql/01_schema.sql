-- ============================================================
-- pg-xerp  01_schema.sql — platform schema (PostgreSQL 16+)
-- Mirrors xErp's SQL Server security/menu/company model, 1:1.
-- Fast-grid contract: every list reads rows + total in ONE query
-- (count(*) OVER () AS rc) so even million-row tables render in
-- a single round-trip. No separate COUNT pass, ever.
-- ============================================================
BEGIN;

/* ---------------- Users ---------------- */
CREATE TABLE IF NOT EXISTS "tblHO_User" (
    "UserId"      text PRIMARY KEY,
    "UserName"    text NOT NULL DEFAULT '',
    "PasswordHash" text,
    "Designation" text NOT NULL DEFAULT '',
    "GRP"         text NOT NULL DEFAULT '',
    "Department"  text NOT NULL DEFAULT '',
    "Status"      text NOT NULL DEFAULT '1',
    "token"       text,
    "User_Id"     text NOT NULL DEFAULT '',
    "Created_At"  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_user_token ON "tblHO_User" ("token");
CREATE INDEX IF NOT EXISTS idx_user_login ON "tblHO_User" (lower(btrim("UserId")));

/* ---------------- Departments & Groups ---------------- */
CREATE TABLE IF NOT EXISTS "tblSecDepartment" (
    "DeptId"      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeptName"    text NOT NULL UNIQUE,
    "Active"      boolean NOT NULL DEFAULT true,
    "FCODE"       text NOT NULL DEFAULT 'HO',
    "LOCK"        boolean NOT NULL DEFAULT false,
    "LOCK_User_Id" text NOT NULL DEFAULT '',
    "User_Id"     text NOT NULL DEFAULT '',
    "Created_At"  timestamptz NOT NULL DEFAULT now(),
    "Attachments" integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS "tblSecGroup" (
    "GrpId"       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "GrpName"     text NOT NULL UNIQUE,
    "IsAdmin"     boolean NOT NULL DEFAULT false,
    "Active"      boolean NOT NULL DEFAULT true,
    "FCODE"       text NOT NULL DEFAULT 'HO',
    "LOCK"        boolean NOT NULL DEFAULT false,
    "LOCK_User_Id" text NOT NULL DEFAULT '',
    "User_Id"     text NOT NULL DEFAULT '',
    "Created_At"  timestamptz NOT NULL DEFAULT now(),
    "Attachments" integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS "tblSecUserDept" (
    "UserId" text NOT NULL,
    "DeptId" bigint NOT NULL,
    PRIMARY KEY ("UserId", "DeptId")
);

CREATE TABLE IF NOT EXISTS "tblSecUserGrp" (
    "UserId" text NOT NULL,
    "GrpId"  bigint NOT NULL,
    PRIMARY KEY ("UserId", "GrpId")
);

/* ---------------- Menu scope + per-form permissions ---------------- */
CREATE TABLE IF NOT EXISTS "tblSecMenuScope" (
    "Id"       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ScopeType" text NOT NULL,          -- U=user, G=group, D=dept
    "ScopeId"  text NOT NULL,
    "WebPage"  text NOT NULL,
    "Visible"  boolean NOT NULL DEFAULT true,
    "MenuOrder" integer
);
CREATE INDEX IF NOT EXISTS idx_ms_scope ON "tblSecMenuScope" ("ScopeType", "ScopeId");
CREATE INDEX IF NOT EXISTS idx_ms_webpage ON "tblSecMenuScope" ("WebPage");

CREATE TABLE IF NOT EXISTS "tblSecPerm" (
    "Id"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ScopeType" text NOT NULL,
    "ScopeId"   text NOT NULL,
    "Form_Id"   text NOT NULL,
    "Ur_S" boolean, "Ur_P" boolean, "Ur_D" boolean, "Ur_U" boolean,
    "Ur_V" boolean, "Ur_X" boolean, "Ur_M" boolean, "Ur_L" boolean,
    "Ur_UnL" boolean, "Ur_Cancel" boolean, "Ur_UnCancel" boolean,
    "Ur_SMS" boolean, "Ur_showAll" boolean,
    "Created_At" timestamptz NOT NULL DEFAULT now(),
    "User_Id"    text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_perm_form ON "tblSecPerm" ("Form_Id", "ScopeType", "ScopeId");

/* ---------------- Web menus ---------------- */
CREATE TABLE IF NOT EXISTS "tblWebMenus" (
    "Id"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "MainGroup"   text NOT NULL DEFAULT 'MAIN',
    "SubGroup"    text NOT NULL,
    "MenuTitle"   text NOT NULL,
    "WebPage"     text NOT NULL,
    "DisplayIcon" text NOT NULL DEFAULT 'bi-window',
    "ShowStatus"  boolean NOT NULL DEFAULT true,
    "MenuOrder"   integer NOT NULL DEFAULT 99,
    "FCODE"       text NOT NULL DEFAULT 'HO',
    "AdminOnly"   boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_wm_fcode ON "tblWebMenus" ("FCODE", "ShowStatus");
CREATE INDEX IF NOT EXISTS idx_wm_webpage ON "tblWebMenus" ("WebPage");

/* ---------------- Companies (franchisee -> FCODE) ---------------- */
CREATE TABLE IF NOT EXISTS "tblHO_Franchisee" (
    "Id"             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FranchiseeCode" text,
    "Company"        text NOT NULL DEFAULT '',
    "Name"           text NOT NULL DEFAULT '',
    "FranchiseeStatus" text NOT NULL DEFAULT '',
    "Status"         text NOT NULL DEFAULT '1',
    "User_Id"        text NOT NULL DEFAULT '',
    "Created_At"     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_fr_code ON "tblHO_Franchisee" (lower(btrim("FranchiseeCode")));

/* ---------------- User grid preferences ---------------- */
CREATE TABLE IF NOT EXISTS "tblUserSetting" (
    "Id"         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId"     text NOT NULL,
    "FormId"     text NOT NULL,
    "SettingKey" text NOT NULL DEFAULT '',
    "SettingVal" text,
    "Updated_At" timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_us_uniq ON "tblUserSetting" ("UserId", "FormId", "SettingKey");

/* ---------------- Sample business table (proves fast-grid) ---------------- */
CREATE TABLE IF NOT EXISTS "tblBrand" (
    "Id"       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "BrandName" text NOT NULL,
    "FCODE"    text NOT NULL DEFAULT 'HO',
    "LOCK"     boolean NOT NULL DEFAULT false,
    "User_Id"  text NOT NULL DEFAULT '',
    "Created_At" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_brand_name ON "tblBrand" (lower(btrim("BrandName")));
CREATE INDEX IF NOT EXISTS idx_brand_fcode ON "tblBrand" ("FCODE", "Id");

COMMIT;