DROP FUNCTION IF EXISTS public.sp_frmItem_Grid2(integer, integer, text, text, text, text) CASCADE;
DROP FUNCTION IF EXISTS public.sp_frmItem_GridCount1(text, text, text, text) CASCADE;
DROP FUNCTION IF EXISTS public.sp_frmItem_DFE1(bigint, text, text, text) CASCADE;
DROP FUNCTION IF EXISTS public.sp_frmItem_SAVE(text, text, text, jsonb) CASCADE;
DROP FUNCTION IF EXISTS public.sp_frmItem_UPDATE(text, text, text, bigint, jsonb) CASCADE;
DROP FUNCTION IF EXISTS public.sp_frmItem_Delete1(text, text, text, bigint) CASCADE;
DROP FUNCTION IF EXISTS public.sp_frmItem_LockUnlock1(text, text, text, bigint) CASCADE;

CREATE TABLE IF NOT EXISTS public."tblfrmItem" (
    "Id"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Item" text NOT NULL DEFAULT '',
    "FCODE"     text NOT NULL DEFAULT '',
    "User_Id"   text NOT NULL DEFAULT '',
    "Lock"      smallint NOT NULL DEFAULT 0,
    "LOCK_User_Id" text NOT NULL DEFAULT '',
    "Created_At" timestamptz NOT NULL DEFAULT now()
);

CREATE OR REPLACE FUNCTION public.sp_frmItem_Grid2(
    p_pagesize integer, p_pageno integer, p_search text,
    p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("Id" bigint, "Detail" text, "rc" bigint)
LANGUAGE plpgsql AS $function$
BEGIN
    RETURN QUERY
    SELECT t."Id", t.det, count(*) OVER() AS rc
    FROM (
        SELECT r."Id",
               json_build_object('Item', r."Item")::text AS det
        FROM public."tblfrmItem" r
        WHERE (p_search = '' OR r."Item" ILIKE '%' || p_search || '%')
        ORDER BY r."Id" DESC
        LIMIT p_pagesize OFFSET (p_pageno - 1) * p_pagesize
    ) t;
END $function$;

CREATE OR REPLACE FUNCTION public.sp_frmItem_GridCount1(
    p_search text, p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("rc" bigint) LANGUAGE plpgsql AS $function$
BEGIN
    RETURN QUERY SELECT count(*)::bigint FROM public."tblfrmItem";
END $function$;

CREATE OR REPLACE FUNCTION public.sp_frmItem_DFE1(
    p_id bigint, p_formid text, p_auth text, p_fcode text)
RETURNS TABLE("Id" bigint, "Detail" text)
LANGUAGE plpgsql AS $function$
BEGIN
    RETURN QUERY
    SELECT r."Id", json_build_object('Item', r."Item")::text
    FROM public."tblfrmItem" r
    WHERE r."Id" = p_id;
END $function$;

CREATE OR REPLACE FUNCTION public.sp_frmItem_SAVE(
    p_item text, p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("status" text, "message" text, "id" bigint)
LANGUAGE plpgsql AS $function$
DECLARE v_id bigint;
BEGIN
    INSERT INTO public."tblfrmItem" ("Item")
    VALUES (p_item)
    RETURNING "Id" INTO v_id;
    RETURN QUERY SELECT 'Success'::text, ''::text, v_id;
END $function$;

CREATE OR REPLACE FUNCTION public.sp_frmItem_UPDATE(
    p_id bigint, p_item text, p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("status" text, "message" text)
LANGUAGE plpgsql AS $function$
BEGIN
    IF EXISTS (SELECT 1 FROM public."tblfrmItem" WHERE "Id" = p_id AND "Lock" = 1) THEN
        RETURN QUERY SELECT 'Error'::text, 'RECORD IS LOCKED !!!'::text;
        RETURN;
    END IF;
    UPDATE public."tblfrmItem" SET "Item" = p_item WHERE "Id" = p_id;
    RETURN QUERY SELECT 'Success'::text, ''::text;
END $function$;

CREATE OR REPLACE FUNCTION public.sp_frmItem_Delete1(
    p_id bigint, p_formid text, p_auth text)
RETURNS TABLE("status" text, "message" text)
LANGUAGE plpgsql AS $function$
BEGIN
    IF EXISTS (SELECT 1 FROM public."tblfrmItem" WHERE "Id" = p_id AND "Lock" = 1) THEN
        RETURN QUERY SELECT 'Error'::text, 'RECORD IS LOCKED !!!'::text;
        RETURN;
    END IF;
    DELETE FROM public."tblfrmItem" WHERE "Id" = p_id;
    RETURN QUERY SELECT 'Success'::text, ''::text;
END $function$;

CREATE OR REPLACE FUNCTION public.sp_frmItem_LockUnlock1(
    p_formid text, p_auth text, p_company text, p_id bigint)
RETURNS TABLE("status" text, "message" text) LANGUAGE plpgsql AS $function$
BEGIN
    UPDATE public."tblfrmItem" SET "Lock" = CASE WHEN "Lock" = 0 THEN 1 ELSE 0 END
    WHERE "Id" = p_id;
    RETURN QUERY SELECT 'Success'::text, ''::text;
END $function$;
