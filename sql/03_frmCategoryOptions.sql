-- pg-xerp · frmCategoryOptions data layer (PostgreSQL dialect)
-- Transliterated template = pg's OWN proven fast-grid dialect
--   (sp_brand_grid2 = 88ms @ 100k rows, verbatim on pg :3100).
-- Contract: pg's crud.js resolves sps by EXACT name from form.json
--   (already grafted: sp_frmCategoryOptions_Grid2 etc. — satisfied below).
-- ============================================================

-- ------------------------------------------------------------------
-- 1) TABLE (pg's established master-table conventions — Id identity,
--    FCODE company scoping, Lock, audit columns; mirrors tblBrand)
-- ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."tblCategoryOptions" (
    "Id"        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FCODE"     text NOT NULL DEFAULT '',
    "Category"  text NOT NULL DEFAULT '',
    "fldName"   text NOT NULL DEFAULT '',
    "Lock"      smallint NOT NULL DEFAULT 0,
    "User_Id"   text NOT NULL DEFAULT '',
    "Created_At" timestamptz NOT NULL DEFAULT now(),
    "LOCK_User_Id" text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS idx_tblCategoryOptions_category
    ON public."tblCategoryOptions" ("Category");
CREATE INDEX IF NOT EXISTS idx_tblCategoryOptions_fldname
    ON public."tblCategoryOptions" ("fldName");

-- ------------------------------------------------------------------
-- 2) BOOT — but this form has no detail grid; keep contract shape
-- ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_Boot(
    p_formid text, p_auth text, p_fcode text)
RETURNS TABLE("rc" bigint) LANGUAGE plpgsql AS $function$
BEGIN
    RETURN QUERY SELECT 1::bigint;
END $function$;

-- ------------------------------------------------------------------
-- 3) GRID — the exact pg fast-grid dialect (verbatim sp_brand_grid2
--    shape): LIMIT/OFFSET paging + count(*) OVER() single-pass total
-- ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_Grid2(
    p_pagesize integer, p_pageno integer, p_search text,
    p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("Id" bigint, "Category" text, "fldName" text, rc bigint)
LANGUAGE plpgsql AS $function$
BEGIN
    RETURN QUERY
    SELECT c."Id", c."Category", c."fldName", count(*) OVER() AS rc
    FROM public."tblCategoryOptions" c
    WHERE (p_fcode = '' OR c."FCODE" = p_fcode)
      AND (p_search = ''
           OR c."Category" ILIKE '%' || p_search || '%'
           OR c."fldName" ILIKE '%' || p_search || '%')
    ORDER BY c."Id" DESC
    LIMIT p_pagesize OFFSET (p_pageno - 1) * p_pagesize;
END $function$;

-- gridCount (pg contract; some builds call GridCount1)
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_GridCount1(
    p_search text, p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("TotalPages" bigint) LANGUAGE plpgsql AS $function$
BEGIN
    RETURN QUERY
    SELECT count(*)::bigint AS "TotalPages"
    FROM public."tblCategoryOptions" c
    WHERE (p_fcode = '' OR c."FCODE" = p_fcode)
      AND (p_search = ''
           OR c."Category" ILIKE '%' || p_search || '%'
           OR c."fldName" ILIKE '%' || p_search || '%');
END $function$;

-- ------------------------------------------------------------------
-- 4) DFE1 — return one blank row (Add form's boot)
-- ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_DFE1(
    p_id bigint, p_formid text, p_auth text)
RETURNS TABLE("Id" bigint, "Category" text, "fldName" text, "Lock" smallint,
              "FCODE" text, "User_Id" text)
LANGUAGE plpgsql AS $function$
BEGIN
    RETURN QUERY
    SELECT id::bigint, 'New'::text, ''::text, 0::smallint, ''::text, ''::text
    FROM (SELECT p_id AS id) s;
END $function$;

-- ------------------------------------------------------------------
-- 5) SAVE (add) — dup-category guard + insert, pg exception pattern
--    (transliterated from pg's own sp_brand_save error contract)
-- ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_SAVE(
    p_category text, p_fldname text, p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("status" text, "message" text, "id" bigint)
LANGUAGE plpgsql AS $function$
DECLARE v_id bigint;
BEGIN
    IF btrim(coalesce(p_category,'')) = '' THEN
        RETURN QUERY SELECT 'Error'::text, 'Category is required'::text, 0::bigint;
        RETURN;
    END IF;
    IF EXISTS (SELECT 1 FROM public."tblCategoryOptions"
               WHERE lower("Category") = lower(btrim(p_category))
                 AND "FCODE" = p_fcode) THEN
        RETURN QUERY SELECT 'Error'::text, 'Category already exists'::text, 0::bigint;
        RETURN;
    END IF;
    INSERT INTO public."tblCategoryOptions" ("Category","fldName","FCODE","User_Id")
    VALUES (btrim(p_category), coalesce(btrim(p_fldname),''), p_fcode, p_auth)
    RETURNING "Id" INTO v_id;
    RETURN QUERY SELECT 'Success'::text, ''::text, v_id;
EXCEPTION WHEN unique_violation THEN
    RETURN QUERY SELECT 'Error'::text, 'Category already exists'::text, 0::bigint;
END $function$;

-- ------------------------------------------------------------------
-- 6) UPDATE — locked-row guard + update (sp_brand_update contract)
-- ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_UPDATE(
    p_id bigint, p_category text, p_fldname text,
    p_formid text, p_fcode text, p_auth text)
RETURNS TABLE("status" text, "message" text)
LANGUAGE plpgsql AS $function$
BEGIN
    IF EXISTS (SELECT 1 FROM public."tblCategoryOptions" WHERE "Id" = p_id AND "Lock" = 1) THEN
        RETURN QUERY SELECT 'Error'::text, 'RECORD IS LOCKED !!!'::text;
        RETURN;
    END IF;
    UPDATE public."tblCategoryOptions"
    SET "Category" = btrim(p_category),
        "fldName"  = coalesce(btrim(p_fldname),''),
        "User_Id"  = p_auth,
        "Created_At" = now()
    WHERE "Id" = p_id;
    RETURN QUERY SELECT 'Success'::text, ''::text;
END $function$;

-- ------------------------------------------------------------------
-- 7) DELETE — locked guard + delete (sp_brand_delete1 contract)
-- ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_Delete1(
    p_id bigint, p_formid text, p_auth text)
RETURNS TABLE("status" text, "message" text)
LANGUAGE plpgsql AS $function$
BEGIN
    IF EXISTS (SELECT 1 FROM public."tblCategoryOptions" WHERE "Id" = p_id AND "Lock" = 1) THEN
        RETURN QUERY SELECT 'Error'::text, 'RECORD IS LOCKED !!!'::text;
        RETURN;
    END IF;
    DELETE FROM public."tblCategoryOptions" WHERE "Id" = p_id;
    IF NOT FOUND THEN
        RETURN QUERY SELECT 'Error'::text, 'Category not found'::text;
        RETURN;
    END IF;
    RETURN QUERY SELECT 'Success'::text, ''::text;
END $function$;

-- ------------------------------------------------------------------
-- 8) LOCK/UNLOCK — toggle (sp_brand_lockunlock1 contract)
-- ------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.sp_frmCategoryOptions_LockUnlock1(
    p_id bigint, p_auth text, p_formid text)
RETURNS TABLE("status" text, "message" text)
LANGUAGE plpgsql AS $function$
BEGIN
    UPDATE public."tblCategoryOptions"
    SET "Lock" = CASE WHEN "Lock" = 0 THEN 1 ELSE 0 END,
        "LOCK_User_Id" = p_auth
    WHERE "Id" = p_id;
    RETURN QUERY SELECT 'Success'::text, ''::text;
END $function$;
