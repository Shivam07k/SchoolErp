DROP FUNCTION IF EXISTS public.sp_sec_link_save(bigint, text, text, text, text, text, integer, boolean);
CREATE FUNCTION public.sp_sec_link_save(
  p_linkid bigint, p_linkname text, p_linktype text, p_formid text,
  p_url text, p_icon text, p_menuorder integer, p_active boolean)
RETURNS TABLE("status" text, "message" text, "LinkId" bigint)
LANGUAGE plpgsql AS $fn$
DECLARE v_id bigint;
BEGIN
  IF btrim(coalesce(p_linkname, '')) = '' THEN
    RETURN QUERY SELECT 'error', 'Link name is required', NULL::bigint;
    RETURN;
  END IF;
  IF btrim(coalesce(p_formid, '')) = '' AND btrim(coalesce(p_url, '')) = '' THEN
    RETURN QUERY SELECT 'error', 'Pick a form or enter a URL', NULL::bigint;
    RETURN;
  END IF;
  IF p_linkid IS NOT NULL AND p_linkid > 0 THEN
    UPDATE public."tblSecLink" AS l
       SET "LinkName" = btrim(p_linkname),
           "LinkType" = coalesce(nullif(btrim(p_linktype), ''), 'FORM'),
           "FormId"   = nullif(btrim(coalesce(p_formid, '')), ''),
           "Url"      = nullif(btrim(coalesce(p_url, '')), ''),
           "Icon"     = nullif(btrim(coalesce(p_icon, '')), ''),
           "MenuOrder" = coalesce(p_menuorder, 0),
           "Active"   = coalesce(p_active, true)
     WHERE l."LinkId" = p_linkid
    RETURNING l."LinkId" INTO v_id;
    IF v_id IS NULL THEN
      RETURN QUERY SELECT 'error', 'Link not found', p_linkid;
      RETURN;
    END IF;
    RETURN QUERY SELECT 'ok', 'Updated', v_id;
    RETURN;
  END IF;
  INSERT INTO public."tblSecLink" AS l
    ("LinkName", "LinkType", "FormId", "Url", "Icon", "MenuOrder", "Active")
    VALUES (btrim(p_linkname), coalesce(nullif(btrim(p_linktype), ''), 'FORM'),
            nullif(btrim(coalesce(p_formid, '')), ''), nullif(btrim(coalesce(p_url, '')), ''),
            nullif(btrim(coalesce(p_icon, '')), ''), coalesce(p_menuorder, 0), coalesce(p_active, true))
    RETURNING l."LinkId" INTO v_id;
  RETURN QUERY SELECT 'ok', 'Added', v_id;
END
$fn$;

