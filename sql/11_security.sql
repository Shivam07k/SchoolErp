DROP FUNCTION IF EXISTS public.sp_sec_menu_scope_save(text, text, jsonb);
CREATE FUNCTION public.sp_sec_menu_scope_save(p_scopetype text, p_scopeid text, p_items jsonb)
RETURNS TABLE("status" text, "message" text, "count" integer)
LANGUAGE plpgsql AS $fn$
DECLARE
  it        jsonb;
  v_wp      text;
  v_vis     boolean;
  v_ord     integer;
  v_count   integer := 0;
BEGIN
  IF p_scopetype NOT IN ('U', 'G', 'D') THEN
    RETURN QUERY SELECT 'error', 'Invalid scope type', 0;
    RETURN;
  END IF;
  IF btrim(coalesce(p_scopeid, '')) = '' THEN
    RETURN QUERY SELECT 'error', 'Scope id is required', 0;
    RETURN;
  END IF;
  FOR it IN SELECT * FROM jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) LOOP
    v_wp := it->>'webPage';
    v_vis := coalesce((it->>'visible')::boolean, true);
    v_ord := (it->>'order')::integer;
    CONTINUE WHEN v_wp IS NULL OR btrim(v_wp) = '';
    INSERT INTO public."tblSecMenuScope" ("ScopeType", "ScopeId", "WebPage", "Visible", "MenuOrder")
    VALUES (p_scopetype, p_scopeid, v_wp, v_vis, v_ord)
    ON CONFLICT DO NOTHING;
    v_count := v_count + 1;
  END LOOP;
  /* the screen sends the full visible set, so anything it omitted is now hidden */
  UPDATE public."tblSecMenuScope" s
     SET "Visible" = false
   WHERE s."ScopeType" = p_scopetype AND s."ScopeId" = p_scopeid
     AND NOT EXISTS (SELECT 1 FROM jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) x
                      WHERE x->>'webPage' = s."WebPage");
  RETURN QUERY SELECT 'ok', 'Saved', v_count;
END
$fn$;

DROP FUNCTION IF EXISTS public.sp_sec_user_get(text);
CREATE FUNCTION public.sp_sec_user_get(p_userid text)
RETURNS TABLE("UserId" text, "UserName" text, "Designation" text, "Status" text,
               "hasPassword" boolean, "depts" jsonb, "grps" jsonb)
LANGUAGE sql AS $fn$
  SELECT u."UserId", coalesce(u."UserName", ''), coalesce(u."Designation", ''),
         coalesce(u."Status", '1'), u."PasswordHash" IS NOT NULL,
         coalesce((SELECT jsonb_agg(jsonb_build_object('DeptId', d."DeptId", 'DeptName', d."DeptName") ORDER BY d."DeptName")
                     FROM public."tblSecUserDept" x
                     JOIN public."tblSecDepartment" d ON d."DeptId" = x."DeptId"
                    WHERE x."UserId" = u."UserId"), '[]'::jsonb),
         coalesce((SELECT jsonb_agg(jsonb_build_object('GrpId', g."GrpId", 'GrpName', g."GrpName") ORDER BY g."GrpName")
                     FROM public."tblSecUserGrp" y
                     JOIN public."tblSecGroup" g ON g."GrpId" = y."GrpId"
                    WHERE y."UserId" = u."UserId"), '[]'::jsonb)
  FROM public."tblHO_User" u
  WHERE u."UserId" = p_userid;
$fn$;

DROP FUNCTION IF EXISTS public.sp_company_save(bigint, text, text, text, text);
CREATE FUNCTION public.sp_company_save(
  p_id bigint, p_franchiseecode text, p_company text, p_name text, p_status text)
RETURNS TABLE("status" text, "message" text, "Id" bigint)
LANGUAGE plpgsql AS $fn$
DECLARE v_id bigint;
BEGIN
  IF btrim(coalesce(p_franchiseecode, '')) = '' THEN
    RETURN QUERY SELECT 'error', 'Franchisee Code required', NULL::bigint;
    RETURN;
  END IF;
  IF btrim(coalesce(p_company, '')) = '' THEN
    RETURN QUERY SELECT 'error', 'Company name required', NULL::bigint;
    RETURN;
  END IF;
  IF p_id IS NOT NULL AND p_id > 0 THEN
    UPDATE public."tblHO_Franchisee" AS f
       SET "Company" = btrim(p_company),
           "Name" = coalesce(nullif(btrim(coalesce(p_name, '')), ''), "Name"),
           "Status" = coalesce(nullif(btrim(coalesce(p_status, '')), ''), "Status")
     WHERE f."Id" = p_id
    RETURNING f."Id" INTO v_id;
    IF v_id IS NULL THEN
      RETURN QUERY SELECT 'error', 'Company not found', p_id;
      RETURN;
    END IF;
    RETURN QUERY SELECT 'ok', 'Updated', v_id;
    RETURN;
  END IF;
  SELECT f."Id" INTO v_id FROM public."tblHO_Franchisee" f
   WHERE btrim(f."FranchiseeCode") = btrim(p_franchiseecode);
  IF v_id IS NOT NULL THEN
    RETURN QUERY SELECT 'error', 'Franchisee code already exists', v_id;
    RETURN;
  END IF;
  INSERT INTO public."tblHO_Franchisee" AS f ("FranchiseeCode", "Company", "Name", "Status", "FranchiseeStatus")
    VALUES (btrim(p_franchiseecode), btrim(p_company), btrim(coalesce(p_name, '')),
            coalesce(nullif(btrim(coalesce(p_status, '')), ''), '1'), '1')
    RETURNING f."Id" INTO v_id;
  RETURN QUERY SELECT 'ok', 'Added', v_id;
END
$fn$;

DROP FUNCTION IF EXISTS public.sp_dashboard_links(text, text);
CREATE FUNCTION public.sp_dashboard_links(p_admin text, p_token text)
RETURNS TABLE("WebPage" text, "MenuTitle" text)
LANGUAGE plpgsql AS $fn$
DECLARE v_uid text; v_admin boolean := false;
BEGIN
  IF p_token IS NOT NULL THEN
    SELECT "UserId" INTO v_uid FROM "tblHO_User" WHERE "token"=p_token LIMIT 1;
    IF v_uid IS NOT NULL THEN
      IF EXISTS (SELECT 1 FROM "tblSecUserGrp" x JOIN "tblSecGroup" g ON g."GrpId"=x."GrpId"
                 WHERE x."UserId"=v_uid AND g."IsAdmin")
         OR EXISTS (SELECT 1 FROM "tblHO_User" u WHERE u."UserId"=v_uid AND u."GRP" ILIKE '%ADMIN%')
         OR v_uid='ADMIN'
      THEN v_admin := true; END IF;
    END IF;
  END IF;

  /* ShowOnDashboard was added for frmSecLink's menu editor; the coalesce keeps
     every pre-existing row visible exactly as it behaved before. The WebPage
     match is made on the stripped name because that is what the scope screens
     store - they read formId from /dashboard, which has no .aspx suffix. */
  RETURN QUERY
  SELECT replace(m."WebPage", '.aspx', ''), m."MenuTitle"
  FROM "tblWebMenus" m
  WHERE m."ShowStatus" AND coalesce(m."ShowOnDashboard", true)
    AND NOT coalesce(m."AdminOnly", false)
    AND (v_uid IS NULL OR v_admin OR NOT EXISTS (
      SELECT 1 FROM "tblSecMenuScope" h
      WHERE replace(h."WebPage", '.aspx', '') = replace(m."WebPage", '.aspx', '')
        AND NOT h."Visible"
        AND (
          (h."ScopeType"='U' AND h."ScopeId"=v_uid)
          OR (h."ScopeType"='G' AND h."ScopeId" IN (SELECT * FROM my_grp_ids(v_uid)))
          OR (h."ScopeType"='D' AND h."ScopeId" IN (SELECT * FROM my_dept_ids(v_uid)))
        )
    ))
  ORDER BY m."SubGroup", m."MenuOrder";
END
$fn$;
