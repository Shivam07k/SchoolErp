/* ------------------------------------------------------------------
   Security / admin pages: the functions behind the security REST surface.

   The seven security screens (frmSecUser, frmSecDept, frmSecGrp,
   frmSecMenu, frmSecPerm, frmSecLink, frmCompany) do not use the
   Grid2/SAVE procs like the business forms do. They call a small REST
   surface instead, because a user/group/department is a security object
   rather than a document: it is looked up by natural key, edited through
   a form, and read by the menu and rights resolvers rather than by a
   pager. Those endpoints existed for users, companies and permissions
   only, so the department, group, link, menu and menu-scope screens had
   nothing to call.

   Naming follows the rest of the port: sp_<area>_<verb>. No CREATE
   PROCEDURE anywhere - everything is a function so it can be called
   through the same execFn path as the form procs.
   ------------------------------------------------------------------ */

CREATE TABLE IF NOT EXISTS public."tblSecDepartment" (
  "DeptId"   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "DeptName" text NOT NULL,
  "Active"   boolean NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX IF NOT EXISTS "idx_tblSecDepartment_Name"
  ON public."tblSecDepartment" (lower(btrim("DeptName")));

CREATE TABLE IF NOT EXISTS public."tblSecLink" (
  "LinkId"    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "LinkName"  text NOT NULL,
  "LinkType"  text NOT NULL DEFAULT 'FORM',
  "FormId"    text,
  "Url"       text,
  "Icon"      text,
  "MenuOrder" integer NOT NULL DEFAULT 0,
  "Active"    boolean NOT NULL DEFAULT true
);

ALTER TABLE public."tblWebMenus"
  ADD COLUMN IF NOT EXISTS "ShowOnDashboard" boolean NOT NULL DEFAULT true;
ALTER TABLE public."tblSecDepartment"
  ADD COLUMN IF NOT EXISTS "Active" boolean NOT NULL DEFAULT true;

/* the menu-visibility screen sends the whole visible set and upserts, so the
   natural key has to be unique for ON CONFLICT to mean anything */
CREATE UNIQUE INDEX IF NOT EXISTS "idx_tblSecMenuScope_key"
  ON public."tblSecMenuScope" ("ScopeType", "ScopeId", "WebPage");

CREATE TABLE IF NOT EXISTS public."tblHO_Franchisee_audit" (
  "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "At" timestamptz NOT NULL DEFAULT now(),
  "Actor" text,
  "Action" text,
  "Detail" text
);

DROP FUNCTION IF EXISTS public.sp_sec_dept_list();
CREATE FUNCTION public.sp_sec_dept_list()
RETURNS TABLE("DeptId" bigint, "DeptName" text, "Active" boolean)
LANGUAGE sql AS $fn$
  SELECT d."DeptId", d."DeptName", d."Active"
  FROM public."tblSecDepartment" d
  ORDER BY d."DeptName";
$fn$;

DROP FUNCTION IF EXISTS public.sp_sec_dept_save(text);
CREATE FUNCTION public.sp_sec_dept_save(p_name text)
RETURNS TABLE("status" text, "message" text, "DeptId" bigint)
LANGUAGE plpgsql AS $fn$
DECLARE v_id bigint;
BEGIN
  IF btrim(coalesce(p_name, '')) = '' THEN
    RETURN QUERY SELECT 'error', 'Department name is required', NULL::bigint;
    RETURN;
  END IF;
  SELECT d."DeptId" INTO v_id FROM public."tblSecDepartment" d
   WHERE lower(btrim(d."DeptName")) = lower(btrim(p_name));
  IF v_id IS NOT NULL THEN
    RETURN QUERY SELECT 'error', 'Department already exists', v_id;
    RETURN;
  END IF;
  INSERT INTO public."tblSecDepartment" AS d ("DeptName") VALUES (btrim(p_name))
    RETURNING d."DeptId" INTO v_id;
  RETURN QUERY SELECT 'ok', 'Added', v_id;
END
$fn$;

DROP FUNCTION IF EXISTS public.sp_sec_dept_delete(bigint);
CREATE FUNCTION public.sp_sec_dept_delete(p_id bigint)
RETURNS TABLE("status" text, "message" text)
LANGUAGE plpgsql AS $fn$
BEGIN
  DELETE FROM public."tblSecUserDept" WHERE "DeptId" = p_id;
  DELETE FROM public."tblSecMenuScope"
   WHERE "ScopeType" = 'D' AND "ScopeId" = p_id::text;
  DELETE FROM public."tblSecPerm"
   WHERE "ScopeType" = 'D' AND "ScopeId" = p_id::text;
  DELETE FROM public."tblSecDepartment" WHERE "DeptId" = p_id;
  IF NOT FOUND THEN
    RETURN QUERY SELECT 'error', 'Department not found';
  ELSE
    RETURN QUERY SELECT 'ok', 'Deleted';
  END IF;
END
$fn$;

